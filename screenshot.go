const maxScreenshotBytes = 128 * 1024 * 1024
const maxScreenshotPixels = 32 * 1024 * 1024
const maxDraftPictures = 8

type draftPicture struct{ ID, Path string }

func checkScreenshotSize(w, h int64) error {
	if w < 1 || h < 1 || w > 32768 || h > 32768 || w*h > maxScreenshotPixels {
		return errors.New("截图尺寸过大或无效，请缩小截图后重试")
	}
	return nil
}

// decodeScreenshotDIB accepts uncompressed BGR/BGRA Windows clipboard DIBs.
// Never trust offsets, row lengths, dimensions or arbitrary channel masks.
func decodeScreenshotDIB(raw []byte) (image.Image, error) {
	bad := errors.New("剪贴板图片格式不受支持，请重新截图后粘贴")
	if len(raw) < 40 || len(raw) > maxScreenshotBytes {
		return nil, bad
	}
	u16 := func(i int) uint16 { return binary.LittleEndian.Uint16(raw[i:]) }
	u32 := func(i int) uint32 { return binary.LittleEndian.Uint32(raw[i:]) }
	header := int64(u32(0))
	if header != 40 && header != 52 && header != 56 && header != 108 && header != 124 || header > int64(len(raw)) {
		return nil, bad
	}
	w, signedH := int64(int32(u32(4))), int64(int32(u32(8)))
	h := signedH
	if h < 0 {
		h = -h
	}
	if err := checkScreenshotSize(w, h); err != nil {
		return nil, err
	}
	bits, compression := u16(14), u32(16)
	if u16(12) != 1 || bits != 24 && bits != 32 || compression != 0 && compression != 3 || compression == 3 && bits != 32 {
		return nil, bad
	}
	offset := header
	alpha := false
	if compression == 3 {
		if header == 40 {
			offset += 12
		}
		if int64(len(raw)) < offset || u32(40) != 0x00ff0000 || u32(44) != 0x0000ff00 || u32(48) != 0x000000ff {
			return nil, bad
		}
		if header >= 56 {
			a := u32(52)
			if a != 0 && a != 0xff000000 {
				return nil, bad
			}
			alpha = a != 0
		}
	}
	// Non-paletted DIBs may still have an optional color table.
	colors := int64(u32(32))
	if colors > 256 {
		return nil, bad
	}
	offset += colors * 4
	stride := ((w*int64(bits) + 31) / 32) * 4
	if offset+stride*h > int64(len(raw)) {
		return nil, errors.New("剪贴板图片数据不完整，请重新复制")
	}
	img := image.NewNRGBA(image.Rect(0, 0, int(w), int(h)))
	for y := int64(0); y < h; y++ {
		srcY := y
		if signedH > 0 {
			srcY = h - 1 - y
		}
		row := raw[offset+stride*srcY : offset+stride*srcY+stride]
		for x := int64(0); x < w; x++ {
			s, d := x*int64(bits/8), int(y)*img.Stride+int(x)*4
			img.Pix[d], img.Pix[d+1], img.Pix[d+2], img.Pix[d+3] = row[s+2], row[s+1], row[s], 255
			// BI_RGB's fourth byte is reserved, frequently zero. Only an
			// explicit DIBV5 alpha mask may make screenshots transparent.
			if alpha {
				img.Pix[d+3] = row[s+3]
			}
		}
	}
	return img, nil
}

func decodeScreenshotPNG(raw []byte) (image.Image, error) {
	if len(raw) == 0 || len(raw) > maxScreenshotBytes {
		return nil, errors.New("剪贴板图片过大或为空")
	}
	c, err := png.DecodeConfig(bytes.NewReader(raw))
	if err != nil {
		return nil, errors.New("无法读取剪贴板PNG图片")
	}
	if err = checkScreenshotSize(int64(c.Width), int64(c.Height)); err != nil {
		return nil, err
	}
	return png.Decode(bytes.NewReader(raw))
}

func saveDraftScreenshot(stateDir string, img image.Image) (draftPicture, error) {
	if err := checkScreenshotSize(int64(img.Bounds().Dx()), int64(img.Bounds().Dy())); err != nil {
		return draftPicture{}, err
	}
	id := rid(16)
	dir := filepath.Join(stateDir, "image-outbox", id)
	if err := os.MkdirAll(dir, 0700); err != nil {
		return draftPicture{}, err
	}
	path := filepath.Join(dir, "截图-"+time.Now().Format("20060102-150405")+".png")
	f, err := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
	if err != nil {
		os.Remove(dir)
		return draftPicture{}, err
	}
	encoder := png.Encoder{CompressionLevel: png.BestSpeed}
	err = encoder.Encode(f, img)
	closeErr := f.Close()
	if err == nil {
		err = closeErr
	}
	if err != nil {
		os.Remove(path)
		os.Remove(dir)
		return draftPicture{}, fmt.Errorf("保存截图失败：%w", err)
	}
	return draftPicture{id, path}, nil
}

// Only delete files with the exact structure generated by saveDraftScreenshot.
// Files already queued for sending must never be passed here.
func removeDraftScreenshot(stateDir string, p draftPicture) {
	if _, err := hex.DecodeString(p.ID); err != nil || len(p.ID) != 32 || filepath.Base(p.ID) != p.ID {
		return
	}
	dir := filepath.Join(stateDir, "image-outbox", p.ID)
	if filepath.Clean(filepath.Dir(p.Path)) != filepath.Clean(dir) || filepath.Ext(p.Path) != ".png" {
		return
	}
	if os.Remove(p.Path) == nil || !fileExists(p.Path) {
		os.Remove(dir)
	}
}

func fileExists(path string) bool { _, err := os.Stat(path); return err == nil }

func withoutDraftPicture(pictures []draftPicture, id string) []draftPicture {
	result := make([]draftPicture, 0, len(pictures))
	for _, p := range pictures {
		if p.ID != id {
			result = append(result, p)
		}
	}
	return result
}
